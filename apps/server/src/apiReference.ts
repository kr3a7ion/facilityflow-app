/**
 * docs/API.md, generated from the routes the server actually registers.
 *
 * The README's route list was kept by hand and had fallen to about a third of the API. This
 * reads the list off a real app instead: every route, the permission its guard requires, and
 * whether a paired phone may call it. `npm run docs:api` writes the file; the smoke suite
 * fails when it no longer matches, so it cannot drift again.
 */
import fs from 'node:fs';
import os from 'node:os';
import path from 'node:path';
import { fileURLToPath } from 'node:url';
import { openDb } from './db/connection.js';
import { migrate } from './db/migrate.js';
import { buildApp, PHONE_ROUTES, type RouteEntry } from './app.js';
import { loadConfig } from './config.js';
import { ALL_CODES } from './auth/permissions.js';

const here = path.dirname(fileURLToPath(import.meta.url));
const SRC = here.endsWith(`${path.sep}dist`) ? path.resolve(here, '../src') : here;
export const API_DOC = path.resolve(SRC, '../../../docs/API.md');

/** The route files, in the order the reference lists them, with the heading each gets. */
const SECTIONS: [file: string, title: string][] = [
  ['health', 'Health'],
  ['setup', 'First-run setup'],
  ['auth', 'Signing in'],
  ['me', 'The signed-in person, and the event stream'],
  ['alerts', 'Alerts and rings'],
  ['duty', 'Duty devices'],
  ['jobs', 'Jobs and requests'],
  ['ppm', 'Planned maintenance'],
  ['registry', 'Assets, locations and apartments'],
  ['people', 'Staff, roster, handover and notifications'],
  ['power', 'Power and fuel'],
  ['stores', 'Stores'],
  ['money', 'Money'],
  ['safety', 'Safety'],
  ['reports', 'Reports'],
  ['attachments', 'Photos and files'],
  ['exports', 'Exports'],
  ['retire', 'Retiring records'],
  ['admin', 'Administration'],
];

/**
 * The route file each route is defined in, which is what groups the reference. Read from
 * the source rather than the running app, because a closure cannot say where it came from.
 */
function fileOfRoute(): Map<string, string> {
  const out = new Map<string, string>();
  const dir = path.join(SRC, 'routes');
  for (const name of fs.readdirSync(dir).filter((f) => f.endsWith('.ts')).sort()) {
    const text = fs.readFileSync(path.join(dir, name), 'utf8');
    for (const [, method = '', url = ''] of text.matchAll(/app\.(get|post|put|patch|delete)\(\s*'([^']+)'/g)) {
      out.set(`${method.toUpperCase()} ${url}`, name.replace(/\.ts$/, ''));
    }
  }
  return out;
}

/** Ask an unguarded route as nobody: a 401 means it checks for a session itself. */
async function needsWithoutGuard(app: Awaited<ReturnType<typeof buildApp>>, r: RouteEntry): Promise<string> {
  const url = r.url.replace(/:(\w+)/g, 'probe');
  const res = await app.inject({ method: r.method as 'GET', url, ...(r.method === 'GET' ? {} : { payload: {} }) });
  return res.statusCode === 401 ? 'signed in' : 'open';
}

export async function apiReference(): Promise<string> {
  const dir = fs.mkdtempSync(path.join(os.tmpdir(), 'ff-api-'));
  const config = loadConfig({ dataDir: dir });
  const db = openDb(config.dbPath);
  try {
    migrate(db);
    const app = await buildApp(db, config);
    await app.ready();
    const routes = app.routeList.filter((r) => r.url.startsWith('/api/'));
    const needs = new Map<RouteEntry, string>();
    for (const r of routes) needs.set(r, r.requires ?? await needsWithoutGuard(app, r));
    await app.close();

    return render(routes, needs, fileOfRoute(), ALL_CODES.length);
  } finally {
    db.close();
    fs.rmSync(dir, { recursive: true, force: true });
  }
}

function render(
  routes: RouteEntry[], needs: Map<RouteEntry, string>, files: Map<string, string>, permissions: number
): string {
  const key = (r: RouteEntry) => `${r.method} ${r.url}`;
  const lines: string[] = [
    '# API reference',
    '',
    '<!-- Generated by `npm run docs:api` from the routes the server registers. Do not edit by hand:',
    '     the smoke suite fails when this file and the server disagree. -->',
    '',
    `${routes.length} routes. Every one answers JSON, except the event stream and file downloads.`,
    '',
    '**Needs** is what the route checks before it does anything:',
    '',
    `- a \`permission.code\` — one of the ${permissions} in Admin → Roles. Never a role name, so who may do`,
    '  what is a setting, not a release;',
    '- *signed in* — any session, or a paired phone where the phone column allows it;',
    '- *open* — works before anybody signs in.',
    '',
    'Most routes narrow further inside: by scope (own, team or all), by property, by whether the',
    'request came from outside the property. The README\'s table of rules says where each of those',
    'is enforced.',
    '',
    '**Phone** marks the routes a paired phone\'s token may call. Everything else refuses it with',
    '`403 not_for_phones`.',
    '',
    'Lists that grow without limit take `?month=YYYY-MM` and default to the current month in the',
    'property\'s timezone.',
  ];

  const byFile = new Map<string, RouteEntry[]>();
  for (const r of routes) {
    const file = files.get(key(r)) ?? 'other';
    byFile.set(file, [...(byFile.get(file) ?? []), r]);
  }
  const sections = [...SECTIONS, ...[...byFile.keys()]
    .filter((f) => !SECTIONS.some(([s]) => s === f)).sort().map((f) => [f, f] as [string, string])];

  for (const [file, title] of sections) {
    const list = byFile.get(file);
    if (!list?.length) continue;
    lines.push('', `## ${title}`, '', '| Method | Path | Needs | Phone |', '|---|---|---|---|');
    for (const r of list) {
      const need = needs.get(r)!;
      const shown = need === 'signed in' || need === 'open' ? `*${need}*` : `\`${need}\``;
      lines.push(`| ${r.method} | \`${r.url}\` | ${shown} | ${PHONE_ROUTES.has(key(r)) ? 'yes' : ''} |`);
    }
  }
  return lines.join('\n') + '\n';
}
